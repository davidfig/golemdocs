#!/usr/bin/env python3
"""Generates src/fonts/data.ts: standard 14 font metrics, simple-font encodings and a glyph list.

Sources (all freely redistributable):
  - Adobe Core 14 AFM files (the copies shipped with matplotlib: mpl-data/fonts/pdfcorefonts)
  - Adobe Glyph List / AGL for New Fonts, StandardEncoding and MacRoman (as shipped in fontTools)
Usage: python3 scripts/generate-font-data.py <pdfcorefonts dir> > src/fonts/data.ts
"""
import sys, os, codecs
from fontTools import agl
from fontTools.encodings.StandardEncoding import StandardEncoding
from fontTools.encodings.MacRoman import MacRoman

afm_dir = sys.argv[1]

def read_afm(path):
    info, glyphs = {}, []
    in_metrics = False
    for line in open(path, encoding='latin-1'):
        line = line.strip()
        if line.startswith('StartCharMetrics'): in_metrics = True; continue
        if line.startswith('EndCharMetrics'): in_metrics = False; continue
        if in_metrics:
            parts = dict(p.strip().split(' ', 1) for p in line.split(';') if p.strip())
            glyphs.append((int(parts['C']), parts['N'], int(float(parts['WX']))))
        else:
            k, _, v = line.partition(' ')
            info[k] = v
    return info, glyphs

FONTS = ['Helvetica', 'Helvetica-Bold', 'Helvetica-Oblique', 'Helvetica-BoldOblique',
         'Times-Roman', 'Times-Bold', 'Times-Italic', 'Times-BoldItalic',
         'Courier', 'Courier-Bold', 'Courier-Oblique', 'Courier-BoldOblique', 'Symbol', 'ZapfDingbats']

afms = {f: read_afm(os.path.join(afm_dir, f + '.afm')) for f in FONTS}
latin = sorted({n for f in FONTS[:12] for _, n, _ in afms[f][1]})

def enc_list(names):
    return ' '.join(n if n and n != '.notdef' else '.' for n in names)

# Encodings (256 glyph names each; '.' = undefined).
std = [n if n != '.notdef' else '' for n in StandardEncoding]
# fontTools' MacRoman names the control codes; PDF's MacRomanEncoding leaves them (and 127) undefined.
mac = [n if n != '.notdef' and 32 <= c < 127 or c > 127 else '' for c, n in enumerate(MacRoman)]
uv2name = {}
for n in latin:
    u = agl.AGL2UV.get(n)
    if u is None: u = (agl.LEGACY_AGL2UV.get(n) or [None])[0]
    if u is not None and u not in uv2name: uv2name[u] = n
win = []
for c in range(256):
    if c < 32: win.append(''); continue
    try: u = ord(bytes([c]).decode('cp1252'))
    except UnicodeDecodeError: u = None
    name = uv2name.get(u) if u is not None else None
    if c == 0xa0: name = 'space'
    if c == 0xad: name = 'hyphen'
    if c == 0x7f or (u is None and c >= 0x80): name = 'bullet'  # PDF Annex D: undefined codes map to bullet
    win.append(name or '')
sym = [''] * 256
for c, n, _ in afms['Symbol'][1]:
    if 0 <= c < 256: sym[c] = n
zapf = [''] * 256
for c, n, _ in afms['ZapfDingbats'][1]:
    if 0 <= c < 256: zapf[c] = n

# Glyph list: AGLFN + any legacy AGL name used by an encoding or font above.
names = set(agl.AGL2UV)
used = set(std + mac + win + sym) | set(latin)
out = {}
for n in sorted(names | used):
    if not n: continue
    if n in agl.AGL2UV: out[n] = [agl.AGL2UV[n]]
    elif n in agl.LEGACY_AGL2UV: out[n] = agl.LEGACY_AGL2UV[n]

p = print
p('// Generated by scripts/generate-font-data.py; do not edit.')
p('// Adobe Core 14 font metrics (AFM), Adobe Glyph List (AGL/AGLFN), StandardEncoding and MacRomanEncoding.')
p('// Copyright Adobe Systems Incorporated; redistributable under their respective licenses.')
p()
p('/** Glyph names of the standard Latin character set, in the order the width tables use. */')
p(f"export const LATIN_GLYPHS = '{' '.join(latin)}';")
p()
p('export interface StandardFontData {')
p('  ascent: number;\n  descent: number;\n  capHeight: number;\n  xHeight: number;\n  italicAngle: number;')
p('  bbox: [number, number, number, number];\n  fixedPitch: boolean;')
p('  /** Advance widths (1/1000 em): aligned to LATIN_GLYPHS, or "name:width" pairs for Symbol/ZapfDingbats. */')
p('  widths: string;\n}')
p()
p('export const STANDARD_FONTS: Record<string, StandardFontData> = {')
for f in FONTS:
    info, glyphs = afms[f]
    bbox = [int(x) for x in info['FontBBox'].split()]
    if f in ('Symbol', 'ZapfDingbats'):
        widths = ' '.join(f'{n}:{w}' for _, n, w in glyphs)
    else:
        wmap = {n: w for _, n, w in glyphs}
        widths = ' '.join(str(wmap.get(n, 0)) for n in latin)
    p(f"  '{f}': {{ ascent: {int(info.get('Ascender', bbox[3]))}, descent: {int(info.get('Descender', bbox[1]))}, "
      f"capHeight: {int(info.get('CapHeight', bbox[3]))}, xHeight: {int(info.get('XHeight', 0))}, "
      f"italicAngle: {float(info.get('ItalicAngle', 0))}, bbox: [{', '.join(map(str, bbox))}], "
      f"fixedPitch: {'true' if info.get('IsFixedPitch') == 'true' else 'false'}, widths: '{widths}' }},")
p('};')
p()
p("/** 256 glyph names per encoding, space-separated; '.' marks an unused code. */")
p(f"export const STANDARD_ENCODING = '{enc_list(std)}';")
p(f"export const MAC_ROMAN_ENCODING = '{enc_list(mac)}';")
p(f"export const WIN_ANSI_ENCODING = '{enc_list(win)}';")
p(f"export const SYMBOL_ENCODING = '{enc_list(sym)}';")
p(f"export const ZAPF_DINGBATS_ENCODING = '{enc_list(zapf)}';")
p()
p('/** Glyph name to Unicode (hex; ligature names map to several code points joined by "+"). */')
entries = ' '.join(f"{n}:{'+'.join('%04X' % u for u in (v if isinstance(v, list) else [v]))}" for n, v in sorted(out.items()))
p(f"export const GLYPH_LIST = '{entries}';")
